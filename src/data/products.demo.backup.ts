/**
 * Common getter that checks live products from localStorage in browser first,
 * falling back to the authoritative products catalog.
 */
export function getProduct(slug: string): Product | undefined {
  if (typeof window !== "undefined") {
    try {
      const stored = localStorage.getItem("miracle:products");
      if (stored) {
        const parsed: Product[] = JSON.parse(stored);
        const match = parsed.find((p) => p.slug === slug || p.id === slug);
        if (match) return match;
      }
    } catch {}
  }
  return products.find((p) => p.slug === slug || p.id === slug);
}

export function getProductById(id: string): Product | undefined {
  if (typeof window !== "undefined") {
    try {
      const stored = localStorage.getItem("miracle:products");
      if (stored) {
        const parsed: Product[] = JSON.parse(stored);
        const match = parsed.find((p) => p.id === id);
        if (match) return match;
      }
    } catch {}
  }
  return products.find((p) => p.id === id);
}

export function relatedProducts(product: Product): Product[] {
  const currentCatalog = typeof window !== "undefined" ? getLiveCatalog() : products;
  return currentCatalog
    .filter((p) => p.categoryId === product.categoryId && p.id !== product.id)
    .slice(0, 4)
    .concat(
      currentCatalog
        .filter((p) => p.categoryId !== product.categoryId && p.id !== product.id)
        .slice(
          0,
          Math.max(
            0,
            4 -
              currentCatalog.filter(
                (q) => q.categoryId === product.categoryId && q.id !== product.id
              ).length
          )
        )
    );
}

export function categoryProducts(categoryId: string): Product[] {
  const currentCatalog = typeof window !== "undefined" ? getLiveCatalog() : products;
  return currentCatalog.filter((p) => p.categoryId === categoryId);
}

function getLiveCatalog(): Product[] {
  try {
    const stored = localStorage.getItem("miracle:products");
    if (stored) {
      const parsed: Product[] = JSON.parse(stored);
      if (Array.isArray(parsed) && parsed.length > 0) return parsed;
    }
  } catch {}
  return products;
}

